"""Verdicts F1–F3 of protocol frn-v1 from the per-store sums of ``data_frn.forecast_bench``
→ ``docs/experiments/frn-forecast.md`` (generated)."""

from __future__ import annotations

import csv
from collections import defaultdict
from pathlib import Path
from typing import Any

import numpy as np

from data_frn.bootstrap import paired_ci
from data_frn.sums_io import open_text, write_summary
from forecasting.baselines import BASELINES

METHODS = ("mlp", *BASELINES)
LABEL = {"mlp": "FreshMesh MLP + conformal", "mean7": "TB 7 ngày", "seasonal_naive": "Cùng thứ tuần trước",
         "empirical_q28": "Phân vị 28 ngày"}  # fmt: skip
COVERAGE_BAND = (0.75, 0.85)


def load_sums(path: Path) -> tuple[dict[str, dict[str, dict[str, np.ndarray]]], list[str], dict[str, str]]:
    """``{window: {method: {stat: (n_stores,)}}}`` aligned on one sorted store list, plus the stamp."""
    with open_text(path) as fh:
        rows = list(csv.DictReader(fh))
    stores = sorted({r["store"] for r in rows})
    pos = {s: i for i, s in enumerate(stores)}
    out: dict = defaultdict(lambda: defaultdict(lambda: defaultdict(lambda: np.zeros(len(stores)))))
    for r in rows:
        for stat in ("n", "y", "abs_err", "pinball", "covered"):
            out[r["window"]][r["method"]][stat][pos[r["store"]]] += float(r[stat])
    stamp = {k: rows[0][k] for k in ("protocol", "protocol_sha256", "history", "seed")}
    return out, stores, stamp


def pooled(m: dict[str, np.ndarray]) -> dict[str, float]:
    y, n = m["y"].sum(), m["n"].sum()
    return {
        "wape": m["abs_err"].sum() / y,
        "pinball": m["pinball"].sum() / y,
        "coverage": m["covered"].sum() / n,
    }


def verdicts(sums: dict) -> dict[str, Any]:
    cal, test = sums["cal"], sums["test"]
    best = min(BASELINES, key=lambda b: pooled(cal[b])["wape"])  # chosen on CAL, never on TEST
    y = test["mlp"]["y"]
    f1 = paired_ci({"y": y, "a": test["mlp"]["pinball"], "b": test["empirical_q28"]["pinball"]},
                   lambda t: (t["a"] - t["b"]) / t["y"])  # fmt: skip
    f2 = paired_ci({"y": y, "a": test["mlp"]["abs_err"], "b": test[best]["abs_err"]},
                   lambda t: (t["a"] - t["b"]) / t["y"])  # fmt: skip
    cov = pooled(test["mlp"])["coverage"]
    return {
        "best_baseline_on_cal": best,
        "F1": {**f1, "pass": f1["ci_high"] < 0},
        "F2": {**f2, "pass": f2["ci_high"] < 0},
        "F3": {"coverage": cov, "pass": COVERAGE_BAND[0] <= cov <= COVERAGE_BAND[1]},
        "test": {m: pooled(test[m]) for m in METHODS},
        "rows_test": int(test["mlp"]["n"].sum()),
    }


def _n(x: float, nd: int = 4) -> str:
    return f"{x:.{nd}f}".replace(".", ",")


def _int(x: int) -> str:
    return f"{x:,}".replace(",", ".")


def _rel(diff: float, base: float) -> str:
    return _n(100 * diff / base, 1) + "%"


def write_report(paths: dict[str, Path], docs_dir: Path) -> Path:
    """``paths``: {history: sums CSV}; 'recovered' is the primary analysis, others are exploratory."""
    lines = [
        "<!-- GENERATED by `python -m data_frn forecast-report`; do not edit by hand -->",
        "# FreshRetailNet — dự báo so với baseline / forecasting vs baselines (frn-v1 §2)",
        "",
    ]
    summary: dict[str, Any] = {"report": "frn-forecast.md", "primary": "recovered", "histories": {}}
    for history, path in paths.items():
        sums, stores, st = load_sums(path)
        v = verdicts(sums)
        primary = history == "recovered"
        summary |= {"protocol": st["protocol"], "protocol_sha256": st["protocol_sha256"]}
        summary["histories"][history] = {**v, "stores": len(stores)}
        lines += [
            f"## Lịch sử `{history}` — {'chính / primary' if primary else 'thăm dò / exploratory'}", "",
            f"Giao thức `{st['protocol']}` (sha256 `{st['protocol_sha256'][:12]}…`), seed {st['seed']}; "
            f"{len(stores)} cửa hàng, {_int(v['rows_test'])} dòng TEST (ngày không hết hàng, h = 1).",
            "", "| Phương pháp | WAPE | Pinball / nhu cầu TB | Độ phủ P10–P90 |", "|---|---|---|---|",
            *(f"| {LABEL[m]} | {_n(v['test'][m]['wape'])} | {_n(v['test'][m]['pinball'])} | "
              f"{_n(100 * v['test'][m]['coverage'], 1)}% |" for m in METHODS), "",
            f"Baseline tốt nhất chọn trên CAL: **{LABEL[v['best_baseline_on_cal']]}**.", "",
        ]  # fmt: skip
        if primary:
            checks = (("F1", "empirical_q28", "pinball"), ("F2", v["best_baseline_on_cal"], "WAPE"))
            for key, base, what in checks:
                r = v[key]
                ref = v["test"][base]["pinball" if key == "F1" else "wape"]
                verdict = "ĐẠT / PASS" if r["pass"] else "KHÔNG ĐẠT / FAIL"
                lines.append(
                    f"- **{key} {verdict}** — Δ{what} (MLP − {LABEL[base]}) = {_n(r['diff'])} "
                    f"[{_n(r['ci_low'])}; {_n(r['ci_high'])}] (95% CI, bootstrap theo cửa hàng), "
                    f"tức {_rel(r['diff'], ref)} so với baseline."
                )
            cov = v["F3"]["coverage"]
            lines += [f"- F3 (thăm dò): độ phủ P10–P90 của MLP = {_n(100 * cov, 1)}% "
                      f"({'trong' if v['F3']['pass'] else 'ngoài'} khoảng 75–85%).", ""]  # fmt: skip
    lines += [
        "Giới hạn: dữ liệu Dingdong (Trung Quốc), doanh số đã chuẩn hóa ×10, không phải thị trường Việt Nam; "
        "xem `frn-protocol.md`.",
        "",
    ]
    out = Path(docs_dir) / "frn-forecast.md"
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    write_summary(Path(docs_dir) / "frn_forecast_summary.json", summary)
    return out
