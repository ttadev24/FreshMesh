"""Are the forecast explanations right? The simulated chains have a known truth (``data_sim`` effect sizes),
so the drivers and what-ifs of ``forecasting.drivers`` are compared with it:

* weekday: model driver of each forecast row vs the generator's weekday factor relative to the weekly mean;
* promotion and holiday what-ifs: P50 with the covariate switched on vs off, against the generator's uplift.

Medians over every established store × SKU of each area type, for the 7 days after ``SIM_AS_OF``. Output:
``docs/experiments/forecast-drivers-check.md`` (generated, ``python -m forecasting drivers-check``).
"""

from __future__ import annotations

import sqlite3
from collections import defaultdict
from pathlib import Path

import numpy as np

from data_sim import CHAIN_IDS, chain_db_path
from data_sim.catalog import CALENDAR_EFFECTS, DOW_FACTORS, PROMO_UPLIFT
from forecasting.drivers import WEEKDAY_VI
from forecasting.service import forecast_demand

HORIZON = 7


def _true_holiday_pct(area: str) -> float:
    key = "holiday_office_factor" if area == "office" else "holiday_other_factor"
    return 100.0 * (CALENDAR_EFFECTS[key] - 1.0)


def chain_check(chain_id: str, data_dir: Path) -> dict[str, dict]:
    """``{area: {"weekday": [(truth, model)] * 7, "promo": (truth, model), "holiday": (truth, model)}}``."""
    con = sqlite3.connect(chain_db_path(data_dir, chain_id))
    try:
        stores = con.execute("SELECT store_id, area_type FROM stores WHERE is_new = 0").fetchall()
        skus = [r[0] for r in con.execute("SELECT sku_id FROM skus ORDER BY sku_id")]
    finally:
        con.close()
    week: dict[tuple[str, int], list[float]] = defaultdict(list)
    lift: dict[tuple[str, str], list[float]] = defaultdict(list)
    for store_id, area in stores:
        kw = {"data_dir": data_dir, "auto_train": False}
        base = forecast_demand(chain_id, [store_id], skus, HORIZON, explain=True, **kw)
        for name in ("promo", "is_holiday"):
            alt = forecast_demand(chain_id, [store_id], skus, HORIZON, scenario={name: True}, **kw)
            lift[(area, name)] += [100 * (a.p50 - b.p50) / max(b.p50, 1.0) for a, b in zip(alt, base, strict=True)]
        for r in base:
            wd = r.date.weekday()
            week[(area, wd)].append(next((d["delta_pct"] for d in r.drivers if d["key"] == f"dow_{wd}"), 0.0))
    out = {}
    for area in sorted({a for _, a in stores}):
        f = DOW_FACTORS[area]
        mean = sum(f) / 7
        out[area] = {
            "weekday": [(100 * (f[d] / mean - 1), float(np.median(week[(area, d)]))) for d in range(7)],
            "promo": (100 * (PROMO_UPLIFT - 1), float(np.median(lift[(area, "promo")]))),
            "holiday": (_true_holiday_pct(area), float(np.median(lift[(area, "is_holiday")]))),
        }
    return out


def _n(x: float) -> str:
    return f"{x:+.1f}".replace(".", ",")


def write_report(data_dir: Path | str, docs_dir: Path | str) -> Path:
    data_dir, docs_dir = Path(data_dir), Path(docs_dir)
    lines = [
        "<!-- GENERATED by `python -m forecasting drivers-check`; do not edit by hand -->",
        "# Kiểm tra lời giải thích dự báo / forecast explanations vs simulator truth",
        "",
        "Chuỗi mô phỏng có \"sự thật\" đã biết (hệ số của `data_sim`), nên lời giải thích của mô hình "
        "(`forecasting/drivers.py`) được so thẳng với nó. Trung vị trên mọi cửa hàng đã hoạt động × mặt hàng "
        "của từng loại khu vực, 7 ngày sau ngày dữ liệu cuối. Đơn vị: % so với một ngày bình thường.",
        "",
    ]
    for chain_id in CHAIN_IDS:
        lines += [f"## {chain_id}", "", "| Khu vực | Yếu tố | Thật | Mô hình | Lệch |", "|---|---|---|---|---|"]
        errors = []
        for area, res in chain_check(chain_id, data_dir).items():
            rows = [(WEEKDAY_VI[d], *res["weekday"][d]) for d in range(7)]
            rows += [("Khuyến mãi", *res["promo"]), ("Ngày lễ", *res["holiday"])]
            for label, truth, model in rows:
                lines.append(f"| {area} | {label} | {_n(truth)} | {_n(model)} | {_n(model - truth)} |")
            errors += [abs(m - t) for t, m in res["weekday"]]
        lines += ["", f"Sai số tuyệt đối trung bình của yếu tố thứ trong tuần: {_n(float(np.mean(errors)))[1:]} "
                  "điểm %.", ""]  # fmt: skip
    lines += [
        "Đọc kết quả: hiệu ứng là thứ mô hình học được từ lịch sử (tương quan), được nêu kèm mỗi dự báo để "
        "người dùng kiểm tra lại; bảng này cho biết chúng gần sự thật đến đâu trên dữ liệu có đáp án.",
        "",
    ]
    out = docs_dir / "forecast-drivers-check.md"
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return out
