"""Data audit of the pinned FreshRetailNet-50K files → ``docs/experiments/frn-data-audit.md`` (+ per-city CSV).

Streams record batches (bounded memory) and checks the facts the rest of ``data_frn`` relies on: the stockout
window of ``stock_hour6_22_cnt``, the encoding of ``hours_stock_status`` and that hourly sales add up to the day.
"""

from __future__ import annotations

import csv
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

import numpy as np
import pyarrow.parquet as pq

from data_frn import DAY_HOURS, DATASET_ID, FILES, HF_REPO, OUT_OF_STOCK, REVISION
from data_frn.download import ensure_files

COLUMNS = ["dt", "city_id", "store_id", "product_id", "sale_amount", "hours_sale", "hours_stock_status",
           "stock_hour6_22_cnt", "discount"]  # fmt: skip


def audit(data_dir: Path | str) -> dict[str, Any]:
    files = ensure_files(data_dir, fetch=False)
    out: dict[str, Any] = {"files": {}}
    city_rows: Counter = Counter()
    city_censored: Counter = Counter()
    city_stores: dict[int, set] = defaultdict(set)
    window_ok = rows = censored = discounted = 0
    max_sum_diff = 0.0
    oos_sale = [0.0, 0]
    ok_sale = [0.0, 0]
    sample_sales, products, dates = [], set(), set()
    for split, path in files.items():
        pf = pq.ParquetFile(path)
        out["files"][split] = {"rows": pf.metadata.num_rows, "sha256": FILES[split][1]}
        for b in pf.iter_batches(batch_size=500_000, columns=COLUMNS):
            hs = b.column("hours_sale").flatten().to_numpy(zero_copy_only=False).reshape(-1, 24)
            st = b.column("hours_stock_status").flatten().to_numpy(zero_copy_only=False).reshape(-1, 24)
            cnt = b.column("stock_hour6_22_cnt").to_numpy()
            sale = b.column("sale_amount").to_numpy()
            city = b.column("city_id").to_numpy()
            window_ok += int(((st[:, DAY_HOURS] == OUT_OF_STOCK).sum(axis=1) == cnt).sum())
            max_sum_diff = max(max_sum_diff, float(np.abs(hs.sum(axis=1) - sale).max()))
            oos, ok = st == OUT_OF_STOCK, st != OUT_OF_STOCK
            oos_sale[0] += float(hs[oos].sum())
            oos_sale[1] += int(oos.sum())
            ok_sale[0] += float(hs[ok].sum())
            ok_sale[1] += int(ok.sum())
            rows += len(sale)
            censored += int((cnt > 0).sum())
            discounted += int((b.column("discount").to_numpy() < 1).sum())
            sample_sales.append(sale[::25])
            city_rows.update(city.tolist())
            city_censored.update(city[cnt > 0].tolist())
            pairs = np.unique(city.astype(np.int64) * 1_000_000 + b.column("store_id").to_numpy())
            for p in pairs.tolist():
                city_stores[p // 1_000_000].add(p % 1_000_000)
            products.update(np.unique(b.column("product_id").to_numpy()).tolist())
            dates.update(np.unique(b.column("dt").to_numpy(zero_copy_only=False)).tolist())
    q = np.quantile(np.concatenate(sample_sales), [0.25, 0.5, 0.75, 0.95])
    out.update(
        rows=rows,
        days=len(dates),
        first_day=str(min(dates))[:10],
        last_day=str(max(dates))[:10],
        cities=len(city_rows),
        stores=sum(len(v) for v in city_stores.values()),
        products=len(products),
        window_6_21_matches=window_ok / rows,
        hourly_sum_max_abs_diff=max_sum_diff,
        mean_hourly_sale_out_of_stock=oos_sale[0] / max(oos_sale[1], 1),
        mean_hourly_sale_in_stock=ok_sale[0] / max(ok_sale[1], 1),
        censored_day_share=censored / rows,
        discounted_day_share=discounted / rows,
        sale_quantiles={"p25": q[0], "p50": q[1], "p75": q[2], "p95": q[3]},
        per_city=[
            {"city_id": c, "stores": len(city_stores[c]), "rows": city_rows[c],
             "censored_day_share": round(city_censored[c] / city_rows[c], 4)}
            for c in sorted(city_rows, key=lambda c: -len(city_stores[c]))
        ],  # fmt: skip
    )
    return out


def _pct(x: float) -> str:
    return f"{100 * x:.1f}".replace(".", ",") + "%"


def write_report(a: dict[str, Any], docs_dir: Path | str) -> Path:
    docs = Path(docs_dir)
    docs.mkdir(parents=True, exist_ok=True)
    with open(docs / "frn_data_audit_cities.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(a["per_city"][0]))
        w.writeheader()
        w.writerows(a["per_city"])
    sq = a["sale_quantiles"]
    lines = [
        "<!-- GENERATED by `python -m data_frn audit`; do not edit by hand -->",
        "# FreshRetailNet-50K — kiểm tra dữ liệu / data audit",
        "",
        f"Bộ dữ liệu `{DATASET_ID}`: [{HF_REPO}](https://huggingface.co/datasets/{HF_REPO}) (CC BY 4.0), revision "
        f"`{REVISION}`; Wang et al. 2025, arXiv:2505.16319. Dữ liệu thật của chuỗi bán lẻ hàng tươi Trung Quốc, "
        "dùng để kiểm chứng thuật toán, không phải dữ liệu demo.",
        "",
        "| Mục | Giá trị |",
        "|---|---|",
        *(f"| File `{s}` | {f['rows']:,} dòng, sha256 `{f['sha256'][:16]}…` |" for s, f in a["files"].items()),
        f"| Ngày | {a['first_day']} → {a['last_day']} ({a['days']} ngày: 90 train + 7 eval) |",
        f"| Thành phố / cửa hàng / sản phẩm | {a['cities']} / {a['stores']} / {a['products']} |",
        f"| `stock_hour6_22_cnt` = số giờ hết hàng trong giờ 6–21 | {_pct(a['window_6_21_matches'])} số dòng khớp |",
        f"| Tổng doanh số theo giờ = `sale_amount` | sai khác lớn nhất {a['hourly_sum_max_abs_diff']:.1e} |",
        f"| Doanh số TB mỗi giờ khi status = 1 / 0 | {a['mean_hourly_sale_out_of_stock']:.4f} / "
        f"{a['mean_hourly_sale_in_stock']:.4f} → 1 = hết hàng |",
        f"| Ngày có hết hàng trong 6–21h (doanh số bị chặn) | {_pct(a['censored_day_share'])} |",
        f"| Ngày có giảm giá (`discount` < 1) | {_pct(a['discounted_day_share'])} |",
        f"| `sale_amount` P25 / P50 / P75 / P95 (đã chuẩn hóa, không có đơn vị thật) | "
        f"{sq['p25']:.2f} / {sq['p50']:.2f} / {sq['p75']:.2f} / {sq['p95']:.2f} |",
        "",
        "Cửa hàng theo thành phố (chi tiết: `frn_data_audit_cities.csv`): "
        + ", ".join(str(c["stores"]) for c in a["per_city"])
        + ".",
        "",
    ]
    path = docs / "frn-data-audit.md"
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return path
