"""Out-of-sample future demand from the *same* ``data_sim`` process, driven by a new seed.

``data_sim`` does not store the per-store / per-SKU base levels it drew, so they are recovered by replaying
the seed-``data_seed`` generator exactly as ``data_sim.generate.generate_all`` does and recording the
``store_mult`` (``rng.uniform``) and per-SKU lognormal draws made inside ``_simulate_sales``. The replay must
reproduce every ``daily_sales.units`` value of the chain DB, otherwise :class:`ReplayMismatch` is raised.

Future days are then generated by calling the very same ``_simulate_sales`` on a 30-day future calendar,
with a proxy generator that hands back the recorded base draws and delegates every other draw (promotion
starts, NegBin noise) to ``default_rng([seed, 100 + chain_index])``; rain comes from ``simulate_rain`` with
``default_rng([seed, 9001])``. ``_simulate_sales`` normalises its trend to 1.0 on the last calendar day; the
recorded lognormal level is multiplied by ``1 + trend · n/365`` so day ``d`` gets ``1 + trend · d/365``
up to a second-order term (≤ 1e-4 for the simulated trends).
"""

from __future__ import annotations

import dataclasses
import datetime as dt
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np

from data_sim import CHAIN_IDS, SIM_AS_OF, open_chain_db
from data_sim.assumptions import HISTORY_DAYS
from data_sim.calendar_weather import build_calendar, simulate_rain
from data_sim.catalog import CHAINS, SKUS
from data_sim.generate import (
    CALENDAR_FUTURE_DAYS,
    WEATHER_FUTURE_DAYS,
    StoreRow,
    _build_stores,
    _simulate_sales,
    history_dates,
)
from data_sim.locations import pick_store_locations


class ReplayMismatch(RuntimeError):
    """The chain DB was not produced by ``generate_all(seed=data_seed)`` (or was modified)."""


class _ProxyRng:
    """Stand-in for ``numpy.random.Generator`` inside ``_simulate_sales``.

    ``record``: delegate everything, remember the ``uniform`` (store multiplier) and ``lognormal`` (SKU level)
    results. ``inject``: return the remembered values in the same order, delegate everything else.
    """

    def __init__(
        self,
        inner: np.random.Generator,
        *,
        uniforms: list[float] | None = None,
        lognormals: list[float] | None = None,
        level_scale: float = 1.0,
    ):
        self._inner = inner
        self._inject = uniforms is not None
        self.uniforms: list[float] = list(uniforms or [])
        self.lognormals: list[float] = list(lognormals or [])
        self._level_scale = level_scale
        self._u = 0
        self._l = 0

    def uniform(self, *args: Any, **kwargs: Any) -> Any:
        if self._inject:
            self._u += 1
            return self.uniforms[self._u - 1]
        value = self._inner.uniform(*args, **kwargs)
        self.uniforms.append(float(value))
        return value

    def lognormal(self, *args: Any, **kwargs: Any) -> Any:
        if self._inject:
            self._l += 1
            return self.lognormals[self._l - 1] * self._level_scale
        value = self._inner.lognormal(*args, **kwargs)
        self.lognormals.append(float(value))
        return value

    def __getattr__(self, name: str) -> Any:
        return getattr(self._inner, name)


@dataclass(frozen=True)
class ChainProcess:
    """Recovered generator state of one chain: its stores and recorded base draws."""

    chain_id: str
    chain_index: int
    stores: list[StoreRow]
    uniforms: list[float]
    lognormals: list[float]


@dataclass(frozen=True)
class FutureDemand:
    """Demand of every store × SKU on ``dates`` (index 0 = first future day)."""

    chain_id: str
    seed: int
    dates: list[dt.date]
    store_ids: list[str]
    sku_ids: list[str]
    units: np.ndarray  # (S, K, D) int
    price: np.ndarray  # (S, K, D) realised shelf price (promo price on promo days)
    promo: np.ndarray  # (S, K, D) 0/1
    rain: np.ndarray  # (D,) mm


def _hist_inputs(data_seed: int) -> tuple[list, np.ndarray, list[tuple[float, float]]]:
    """Same calendar / rain / locations as ``generate_all``."""
    hist = history_dates()
    cal_dates = hist + [SIM_AS_OF + dt.timedelta(days=i) for i in range(1, CALENDAR_FUTURE_DAYS + 1)]
    calendar = build_calendar(cal_dates)
    rain_all = simulate_rain(
        cal_dates[: HISTORY_DAYS + WEATHER_FUTURE_DAYS], np.random.default_rng([data_seed, 9001])
    )
    n_total = sum(len(p.area_types) for p in CHAINS)
    locs = pick_store_locations(n_total, np.random.default_rng([data_seed, 1]))
    return calendar[:HISTORY_DAYS], rain_all[:HISTORY_DAYS], locs


def recover_chain_process(
    chain_id: str, data_seed: int = 42, *, verify_db: Path | None = None
) -> ChainProcess:
    """Replay ``generate_all(seed=data_seed)`` for one chain; optionally check it against the chain DB in
    ``verify_db`` (a data dir) — every historical ``daily_sales`` row must match exactly."""
    if chain_id not in CHAIN_IDS:
        raise ValueError(f"unknown chain_id: {chain_id!r}")
    hist_cal, hist_rain, locs = _hist_inputs(data_seed)
    offset = 0
    for ci, profile in enumerate(CHAINS):
        n = len(profile.area_types)
        if profile.chain_id != chain_id:
            offset += n
            continue
        rng = np.random.default_rng([data_seed, 100 + ci])
        stores = _build_stores(profile, locs[offset : offset + n], rng)
        proxy = _ProxyRng(rng)
        rows, _ = _simulate_sales(profile, stores, hist_cal, hist_rain, proxy)  # type: ignore[arg-type]
        if verify_db is not None:
            _verify_rows(verify_db, chain_id, rows)
        return ChainProcess(chain_id, ci, stores, proxy.uniforms, proxy.lognormals)
    raise ValueError(f"chain {chain_id} not in data_sim.catalog.CHAINS")


def _verify_rows(data_dir: Path, chain_id: str, rows: list[tuple]) -> None:
    con = open_chain_db(data_dir, chain_id, readonly=True)
    try:
        db = {
            (r[0], r[1], r[2]): int(r[3])
            for r in con.execute("SELECT store_id, sku_id, date, units FROM daily_sales")
        }
    finally:
        con.close()
    replay = {(r[0], r[1], r[2]): int(r[3]) for r in rows}
    if replay != db:
        diff = sum(1 for k, v in replay.items() if db.get(k) != v) + len(set(db) - set(replay))
        raise ReplayMismatch(
            f"{chain_id}: replay of the data_sim generator differs from the DB on {diff} daily_sales rows; "
            "regenerate data with the documented data seed"
        )


def future_demand(
    process: ChainProcess,
    seed: int,
    n_days: int = 30,
    *,
    start: dt.date | None = None,
    sku_filter: Callable[[str], bool] | None = None,
) -> FutureDemand:
    """``n_days`` of demand from ``start`` (default ``SIM_AS_OF + 1``) with simulation ``seed``."""
    profile = CHAINS[process.chain_index]
    first = start or SIM_AS_OF + dt.timedelta(days=1)
    dates = [first + dt.timedelta(days=i) for i in range(n_days)]
    cal = build_calendar(dates)
    rain = simulate_rain(dates, np.random.default_rng([seed, 9001]))
    stores = [dataclasses.replace(s, history_days=n_days) for s in process.stores]
    proxy = _ProxyRng(
        np.random.default_rng([seed, 100 + process.chain_index]),
        uniforms=process.uniforms,
        lognormals=process.lognormals,
        level_scale=1.0 + profile.trend_per_year * n_days / 365.0,
    )
    rows, _ = _simulate_sales(profile, stores, cal, rain, proxy)  # type: ignore[arg-type]

    store_ids = [s.store_id for s in process.stores]
    sku_ids = [k.sku_id for k in SKUS if sku_filter is None or sku_filter(k.sku_id)]
    s_pos = {s: i for i, s in enumerate(store_ids)}
    k_pos = {k: i for i, k in enumerate(sku_ids)}
    d_pos = {d.isoformat(): i for i, d in enumerate(dates)}
    shape = (len(store_ids), len(sku_ids), n_days)
    units = np.zeros(shape, dtype=np.int64)
    price = np.zeros(shape)
    promo = np.zeros(shape, dtype=np.int64)
    for store_id, sku_id, day, qty, pr, is_promo, _rain, _src in rows:
        if sku_id not in k_pos:
            continue
        idx = (s_pos[store_id], k_pos[sku_id], d_pos[day])
        units[idx], price[idx], promo[idx] = int(qty), float(pr), int(is_promo)
    return FutureDemand(
        process.chain_id, seed, dates, store_ids, sku_ids, units, price, promo, np.asarray(rain)
    )
