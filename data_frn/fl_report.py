"""Verdict L1 of protocol frn-v1 §5 from ``frn_fl_sums.csv`` → ``frn-fl.md`` and ``frn_fl_summary.json``
(generated). L1 PASS iff the new-store WAPE of FL is below Local with the upper 95% CI bound of the
difference < 0 (bootstrap over new stores, both seeds pooled: a resampling unit is one seed's new store)."""

from __future__ import annotations

import csv
from collections import defaultdict
from pathlib import Path
from typing import Any

import numpy as np

from data_frn.bootstrap import paired_ci
from data_frn.forecast_bench import STATS
from data_frn.sums_io import open_text, write_summary

GROUPS = ("all", "established", "new_store")


def load(path: Path) -> tuple[dict, dict[str, str]]:
    """``{(seed, city, store): {method: {stat: value}, "new": bool}}`` plus the stamp."""
    with open_text(path) as fh:
        rows = list(csv.DictReader(fh))
    units: dict = defaultdict(dict)
    for r in rows:
        u = units[(r["seed"], r["city_id"], r["store_idx"])]
        u["new"] = r["new_store"] == "True"
        u[r["method"]] = {st: float(r[st]) for st in STATS}
    stamp = {k: rows[0][k] for k in ("protocol", "protocol_sha256")}
    return dict(units), stamp


def _metrics(units: list[dict], method: str) -> dict[str, float]:
    tot = {st: sum(u[method][st] for u in units) for st in STATS}
    return {"wape": tot["abs_err"] / tot["y"], "pinball": tot["pinball"] / tot["y"],
            "coverage": tot["covered"] / tot["n"], "n": tot["n"], "stores": len(units)}  # fmt: skip


def verdict(units: dict) -> dict[str, Any]:
    both = [u for u in units.values() if "local" in u and "fl" in u]
    groups = {"all": both, "established": [u for u in both if not u["new"]], "new_store": [u for u in both if u["new"]]}
    metrics = {g: {m: _metrics(us, m) for m in ("local", "fl")} for g, us in groups.items() if us}
    new = groups["new_store"]
    sums = {"y": np.array([u["fl"]["y"] for u in new]), "fl": np.array([u["fl"]["abs_err"] for u in new]),
            "local": np.array([u["local"]["abs_err"] for u in new])}  # fmt: skip
    l1 = paired_ci(sums, lambda t: (t["fl"] - t["local"]) / t["y"])
    return {"metrics": metrics, "L1": {**l1, "pass": l1["ci_high"] < 0}, "seeds": sorted({k[0] for k in units})}


def _n(x: float, nd: int = 4) -> str:
    return f"{x:.{nd}f}".replace(".", ",")


def write_report(path: Path, docs_dir: Path) -> Path:
    units, st = load(path)
    v = verdict(units)
    r = v["L1"]
    label = {"all": "tất cả cửa hàng", "established": "cửa hàng cũ", "new_store": "cửa hàng mới (14 ngày)"}
    lines = [
        "<!-- GENERATED by `python -m data_frn fl-report`; do not edit by hand -->",
        "# FreshRetailNet — học liên kết giữa 18 thành phố / federated learning (frn-v1 §5)",
        "",
        f"Giao thức `{st['protocol']}` (sha256 `{st['protocol_sha256'][:12]}…`), seed {', '.join(v['seeds'])}; "
        "mỗi thành phố là một bên tham gia; 10% cửa hàng mỗi thành phố được làm \"mới\" (lịch sử bắt đầu 14 ngày "
        "trước CAL). Tự học = mô hình F của từng thành phố; liên kết = FedAvg + FedPer với cấu hình đang triển "
        "khai. Chấm trên ngày TEST quan sát được, h = 1.",
        "",
        "| Nhóm | Cửa hàng | WAPE tự học | WAPE liên kết | Pinball tự học | Pinball liên kết | Độ phủ tự học | "
        "Độ phủ liên kết |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for g in GROUPS:
        if g not in v["metrics"]:
            continue
        lo, fl = v["metrics"][g]["local"], v["metrics"][g]["fl"]
        lines.append(f"| {label[g]} | {lo['stores']} | {_n(lo['wape'])} | {_n(fl['wape'])} | {_n(lo['pinball'])} "
                     f"| {_n(fl['pinball'])} | {_n(100 * lo['coverage'], 1)}% | {_n(100 * fl['coverage'], 1)}% |")  # fmt: skip
    verdict_vi = "ĐẠT / PASS" if r["pass"] else "KHÔNG ĐẠT / FAIL"
    lines += [
        "",
        f"**L1 {verdict_vi}** — ΔWAPE cửa hàng mới (liên kết − tự học) = {_n(r['diff'])} "
        f"[{_n(r['ci_low'])}; {_n(r['ci_high'])}] (95% CI, bootstrap theo cửa hàng mới, gộp 2 seed).",
        "",
        "Không chạy: L2 (xu hướng theo số bên tham gia K) và phương án tập trung (tham chiếu): giữ dữ liệu mọi "
        "thành phố cùng lúc vượt bộ nhớ máy chủ dùng chung. Giới hạn: dữ liệu Dingdong (Trung Quốc).",
        "",
    ]
    out = Path(docs_dir) / "frn-fl.md"
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    write_summary(Path(docs_dir) / "frn_fl_summary.json", v | {"report": "frn-fl.md", **st})
    return out
