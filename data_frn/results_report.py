"""``frn-results.md`` (protocol frn-v1 §7, generated): every criterion of frn-v1 and its amendments with its
verdict, read from the JSON twins of the generated reports. A criterion without results is listed as not run,
with the reason; nothing is typed by hand here."""

from __future__ import annotations

import json
import math
from pathlib import Path

PASS, FAIL, NOT_RUN = "ĐẠT / PASS", "KHÔNG ĐẠT / FAIL", "chưa chạy / not run"
L1_NOT_RUN = (
    "18 thành phố cùng lúc vượt bộ nhớ máy chủ dùng chung (7 GB); cần lưu sẵn đặc trưng từng thành phố "
    "ra đĩa trước khi chạy"
)


def _read(docs: Path, name: str) -> dict | None:
    p = docs / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def _n(x: float | None, nd: int = 2) -> str:
    return "—" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.{nd}f}".replace(".", ",")


def _levels(levels: list[dict]) -> str:
    return "; ".join(f"{_n(r['stockout'], 0)}%: {_n(r['diff'])}" for r in levels)


def rows(docs: Path, routing: dict | None) -> list[tuple[str, str, str, str, str]]:
    """(criterion, protocol, verdict, key result, report)."""
    out: list[tuple[str, str, str, str, str]] = []
    f = _read(docs, "frn_forecast_summary.json")
    if f:
        v = f["histories"][f["primary"]]
        t = v["test"]
        for k, what in (("F1", "pinball MLP − q28"), ("F2", "WAPE MLP − baseline tốt nhất")):
            out.append((k, "frn-v1", PASS if v[k]["pass"] else FAIL,
                        f"{what} = {_n(v[k]['diff'], 4)} [{_n(v[k]['ci_low'], 4)}; {_n(v[k]['ci_high'], 4)}]",
                        "frn-forecast.md"))  # fmt: skip
        out.append(("F3 (thăm dò)", "frn-v1", PASS if v["F3"]["pass"] else FAIL,
                    f"độ phủ P10–P90 {_n(100 * v['F3']['coverage'], 1)}%; WAPE MLP "
                    f"{_n(t['mlp']['wape'], 3)}, q28 {_n(t['empirical_q28']['wape'], 3)}",
                    "frn-forecast.md"))  # fmt: skip
    for name, crit, proto, report in (("frn_inventory_summary.json", "I1", "frn-v1", "frn-inventory.md"),
                                      ("frn_inventory_v11_summary.json", "I1′ (sau khi xem)", "frn-v1.1",
                                       "frn-inventory-v1.1.md")):  # fmt: skip
        s = _read(docs, name)
        if s is None:
            out.append((crit, proto, NOT_RUN, "—", report))
            continue
        main = s["shelf_lives"][str(s["primary_shelf_life"])]
        out.append((crit, proto, PASS if main["pass"] else FAIL,
                    f"hàng bỏ − baseline ở hết hàng {_levels(main['levels'])} (điểm %)", report))  # fmt: skip
    e = _read(docs, "frn_elasticity_summary.json")
    out.append(("E (thăm dò)", "frn-v1", NOT_RUN if e is None else (PASS if e["inside_ai_range"] else FAIL),
                "—" if e is None else f"trung vị e = {_n(e['median_elasticity'])} (khoảng AI −3,8 … −1,3)",
                "frn-elasticity.md"))  # fmt: skip
    fl = _read(docs, "frn_fl_summary.json")
    if fl is None:
        out.append(("L1", "frn-v1", NOT_RUN, L1_NOT_RUN, "frn-protocol.md"))
    else:
        r, m = fl["L1"], fl["metrics"]["new_store"]
        out.append(("L1", "frn-v1", PASS if r["pass"] else FAIL,
                    f"WAPE cửa hàng mới: tự học {_n(m['local']['wape'], 4)}, liên kết "
                    f"{_n(m['fl']['wape'], 4)}; Δ = {_n(r['diff'], 4)} [{_n(r['ci_low'], 4)}; "
                    f"{_n(r['ci_high'], 4)}]", "frn-fl.md"))  # fmt: skip
    for key, crit, proto in (("r1", "R1", "frn-v1"), ("r1_v12", "R1′ (sau khi xem)", "frn-v1.2")):
        r = ((routing or {}).get(key) or {}).get("1.3")
        if r is None:
            out.append((crit, proto, NOT_RUN, "—", "routing-benchmark.md"))
            continue
        out.append((crit, proto, PASS if r["pass"] else FAIL,
                    f"PACO ngắn hơn ở {r['paco_shorter_batches']}/{r['batches']} đợt "
                    f"({_n(r['km_saving_pct'], 1)}% km); trễ PACO {r['late_stops']['paco']} vs chia vùng "
                    f"{r['late_stops']['zone_sweep']}",
                    "routing-benchmark.md"))  # fmt: skip
    return out


def write_report(docs_dir: Path | str, routing: dict | None) -> Path:
    docs = Path(docs_dir)
    lines = [
        "<!-- GENERATED by `python -m data_frn results`; do not edit by hand -->",
        "# FreshRetailNet và định tuyến — tổng hợp kết quả / results summary",
        "",
        "Mọi tiêu chí của giao thức đăng ký trước [frn-protocol.md](frn-protocol.md) (`frn-v1`) và các sửa "
        "đổi viết sau khi xem kết quả ([v1.1](frn-protocol-v1.1.md), [v1.2](frn-protocol-v1.2.md)). Kết quả "
        "KHÔNG ĐẠT được báo cáo như kết quả ĐẠT; sửa đổi không đổi kết luận của `frn-v1`.",
        "",
        "| Tiêu chí | Giao thức | Kết luận | Kết quả chính | Báo cáo |",
        "|---|---|---|---|---|",
    ]
    for crit, proto, verdict, result, report in rows(docs, routing):
        lines.append(f"| {crit} | `{proto}` | **{verdict}** | {result} | [{report}]({report}) |")
    lines += ["", "Giới hạn: FreshRetailNet là dữ liệu Dingdong (Trung Quốc), không phải mini-mart Việt Nam; "
              "định tuyến dùng các đợt đơn demo trên vị trí thật OpenStreetMap với đơn do chương trình sinh.",
              ""]  # fmt: skip
    out = docs / "frn-results.md"
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return out
