"""``frn-elasticity.md`` and ``frn_elasticity_summary.json`` (generated) for exploratory E of frn-v1 §4."""

from __future__ import annotations

import math
from pathlib import Path
from typing import Any

from data_frn.elasticity import MIN_OBS
from data_frn.sums_io import write_summary

METHOD_VI = (
    "Ngày không hết hàng; y = log(đơn vị + 1), x = log(tỉ lệ giá); hiệu ứng cố định cửa hàng × sản phẩm và "
    f"thứ trong tuần; OLS theo nhóm hàng có ≥ {MIN_OBS} quan sát; 95% CI bootstrap theo cửa hàng. "
    "Lượng bán ∝ (tỉ lệ giá)^e như trong FreshMesh."
)
LIMIT_VI = (
    "Giới hạn: giảm giá có thể nội sinh (giảm khi bán chậm) nên e bị kéo về 0 hoặc thậm chí dương; "
    "FreshMesh không đổi mặc định chỉ vì kết quả này. Dữ liệu Dingdong (Trung Quốc), không phải thị trường "
    "Việt Nam."
)


def _n(x: float | None, nd: int = 2) -> str:
    return "—" if x is None or math.isnan(x) else f"{x:.{nd}f}".replace(".", ",")


def _int(x: int) -> str:
    return f"{x:,}".replace(",", ".")


def write_report(summary: dict[str, Any], docs_dir: Path) -> Path:
    lo, hi = summary["ai_range"]
    inside = "nằm trong" if summary["inside_ai_range"] else "nằm ngoài"
    lines = [
        "<!-- GENERATED by `python -m data_frn elasticity`; do not edit by hand -->",
        "# FreshRetailNet — hệ số co giãn giá / price elasticity (frn-v1 §4, thăm dò / exploratory)",
        "",
        METHOD_VI,
        "",
        "| Nhóm hàng | Quan sát | Cửa hàng | e | 95% CI |",
        "|---|---|---|---|---|",
    ]
    for r in summary["categories"]:
        ci = f"[{_n(r['ci_low'])}; {_n(r['ci_high'])}]"
        lines.append(f"| {r['category']} | {_int(r['n'])} | {r['stores']} | {_n(r['elasticity'])} | {ci} |")
    med = _n(summary["median_elasticity"])
    lines += ["", f"Trung vị e các nhóm: **{med}**, {inside} khoảng AI đề xuất cho hàng tươi "
              f"({_n(lo, 1)} … {_n(hi, 1)}).", "", LIMIT_VI, ""]  # fmt: skip
    out = Path(docs_dir) / "frn-elasticity.md"
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    write_summary(Path(docs_dir) / "frn_elasticity_summary.json", summary | {"report": "frn-elasticity.md"})
    return out
