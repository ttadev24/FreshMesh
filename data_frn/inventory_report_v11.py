"""Inventory amendments (exploratory, written after the frn-v1 results), each a new FreshMesh family against
the frn-v1 baseline frontier of the same stores (``frn_inventory_sums_L*.csv``):

* ``v11`` (frn-v1.1): the service-target rule on the empirical 28-day quantiles;
* ``v13`` (frn-v1.3): the MLP median in the order-up-to rule.

Output per amendment: ``frn-inventory-v1.X.md``, ``frn_inventory_vXX_frontier.svg`` and
``frn_inventory_vXX_summary.json`` (generated)."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from data_frn.inventory_report import _n, _svg, load, reach_note, verdict
from data_frn.sums_io import write_summary

MLP, BASE = "FreshMesh", "baseline"
AMENDMENTS = {
    "v11": {"version": "1.1", "family": "FreshMesh + q28", "criterion": "I1′",
            "title": "cùng quy tắc đặt hàng, bộ dự báo phân vị 28 ngày"},
    "v13": {"version": "1.3", "family": "FreshMesh P50 × k", "criterion": "I1″",
            "title": "trung vị dự báo MLP trong quy tắc đặt bù tồn (m × P50 trừ tồn)"},
}  # fmt: skip


def _table(levels: list[dict]) -> list[str]:
    rows = ["| Hết hàng | Chênh lệch hàng bỏ (điểm %) | 95% CI | Không xác định |", "|---|---|---|---|"]
    for r in levels:
        ci = f"[{_n(r['ci_low'])}; {_n(r['ci_high'])}]"
        undefined = _n(100 * r["undefined_share"], 1)
        rows.append(f"| {_n(r['stockout'], 0)}% | {_n(r['diff'])} | {ci} | {undefined}% |")
    return rows


def write_report(
    v1_paths: dict[int, Path], amend_paths: dict[int, Path], docs_dir: Path, amendment: str = "v11"
) -> Path:
    a = AMENDMENTS[amendment]
    fam, ver = a["family"], a["version"]
    lines = [
        "<!-- GENERATED by `python -m data_frn inventory-report`; do not edit by hand -->",
        f"# FreshRetailNet — sửa đổi frn-v{ver}: {a['title']}",
        "",
        "**Thăm dò, viết sau khi đã thấy kết quả trước đó** "
        f"([frn-protocol-v{ver}.md](frn-protocol-v{ver}.md)). Không đổi kết luận I1 của frn-v1 "
        "([frn-inventory.md](frn-inventory.md)).",
        "",
    ]
    summary: dict[str, Any] = {"report": f"frn-inventory-v{ver}.md", "primary_shelf_life": 2,
                               "shelf_lives": {}, "family": fam, "criterion": a["criterion"]}  # fmt: skip
    for life in sorted(set(v1_paths) & set(amend_paths), key=lambda x: (x != 2, x)):
        sums, _ = load(amend_paths[life], v1_paths[life])
        _, st = load(amend_paths[life])
        main = verdict(sums, fam, BASE)
        vs_mlp = verdict(sums, fam, MLP)
        role = "chính / primary" if life == 2 else "độ nhạy / sensitivity"
        summary |= {"protocol": st["protocol"], "protocol_sha256": st["protocol_sha256"]}
        summary["shelf_lives"][str(life)] = {
            "levels": main["levels"], "pass": main["pass"], "stores": main["stores"],
            "frontiers": main["frontiers"], "vs_mlp_levels": vs_mlp["levels"],
        }  # fmt: skip
        sha = st["protocol_sha256"][:12]
        lines += [f"## Hạn dùng {life} ngày — {role}", "",
                  f"Giao thức `{st['protocol']}` (sha256 `{sha}…`), {main['stores']} cửa hàng.", "",
                  f"{fam} − baseline (âm là FreshMesh tốt hơn):", "", *_table(main["levels"]), "",
                  f"{fam} − FreshMesh theo mức phục vụ (không có tiêu chí đạt/không đạt):", "",
                  *_table(vs_mlp["levels"]), "", reach_note(main["frontiers"]), ""]  # fmt: skip
        if life == 2:
            verdict_vi = "ĐẠT / PASS" if main["pass"] else "KHÔNG ĐẠT / FAIL"
            lines += [f"**{a['criterion']} {verdict_vi}** (thăm dò, sau khi xem kết quả).", ""]
            svg = f"frn_inventory_{amendment}_frontier.svg"
            _svg(main["frontiers"], Path(docs_dir) / svg)
            lines += [f"![Đường biên: FreshMesh, {fam}, baseline]({svg})", ""]
    out = Path(docs_dir) / f"frn-inventory-v{ver}.md"
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    write_summary(Path(docs_dir) / f"frn_inventory_{amendment}_summary.json", summary)
    return out
